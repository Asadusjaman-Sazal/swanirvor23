/**
 * Two aligned rows: Gallery uses the system photo picker, Files uses the system document picker
 * filtered to images. A dismissed sheet returns nothing and leaves the current picture untouched.
 *
 * This is drawn inside the viewer dialog instead of a second nested window, so the sheet always
 * appears over the picture and dismisses with a tap on the scrim.
 */
@Composable
fun ProfilePictureSourceSheet(
    onDismiss: () -> Unit,
    onGallery: () -> Unit,
    onFiles: () -> Unit
) {
    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(Color.Black.copy(alpha = 0.45f))
            .clickable(onClick = onDismiss),
        contentAlignment = Alignment.BottomCenter
    ) {
        Surface(
            modifier = Modifier
                .fillMaxWidth()
                .navigationBarsPadding(),
            color = Color.White,
            shape = RoundedCornerShape(topStart = 16.dp, topEnd = 16.dp)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 8.dp, bottom = 24.dp)
            ) {
                SourceRow(
                    icon = Icons.Default.PhotoLibrary,
                    label = "Gallery",
                    onClick = onGallery
                )
                SourceRow(
                    icon = Icons.Default.Folder,
                    label = "Files",
                    onClick = onFiles
                )
            }
        }
    }
}

@Composable
private fun SourceRow(
    icon: ImageVector,
    label: String,
    onClick: () -> Unit
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .clickable(onClick = onClick)
            .padding(horizontal = 24.dp, vertical = 16.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        Icon(
            imageVector = icon,
            contentDescription = null,
            tint = Color.Black,
            modifier = Modifier.size(24.dp)
        )
        Spacer(modifier = Modifier.width(16.dp))
        Text(
            text = label,
            style = MaterialTheme.typography.bodyLarge,
            color = Color.Black
        )
    }
}
